/*
 * SC1000 / SC500 - SSD1306 128x64 OLED display
 *
 * Full-screen zoomed waveform of the sample track played with the platter
 * (deck[1]): it scrolls left/right under a fixed centre cursor as you move
 * the jog wheel.
 *
 * WIRING - the OLED shares /dev/i2c-0 with the AS5601 jog sensor (0x36):
 *      SCL -> R13 pad (ROT_SCL)   near the rotary sensor
 *      SDA -> R12 pad (ROT_SDA)
 *      VCC -> 3.3V,  GND -> GND   (e.g. J7 pins 2 / 1)
 * i2c-1 (the J7 EXPANSION bus) is unusable here: on this A13 kernel a bus
 * with no other users goes "cold" and every transfer times out once xwax's
 * realtime audio thread is running. i2c-0 stays alive because the jog is
 * polled hundreds of times a second.
 *
 * To avoid disturbing the jog read (which would glitch the scratch audio),
 * every i2c-0 access is serialised with sc_input.c's i2c0_lock and split
 * into small chunks, so process_rot()'s jog read never waits behind more
 * than one short transfer.
 *
 * The driver never probes/scans - it talks only to OLED_ADDR.
 */


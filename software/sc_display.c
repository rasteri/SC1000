static int   fd = -1;
static int   err_run = 0;

/* stderr goes to a plain file at runtime (see wrapper), which stdio would
 * block-buffer - so flush after every line. */
static void olog(const char *fmt, ...)
{
    va_list ap;
    va_start(ap, fmt);
    vfprintf(stderr, fmt, ap);
    va_end(ap);
    fflush(stderr);
}

static unsigned char fb[OLED_FB_LEN];        /* what we want on screen  */
static unsigned char shadow[OLED_FB_LEN];    /* what is on screen now   */

/* One I2C write, holding i2c0_lock for just this transaction so the jog read
 * in process_rot() only ever waits behind one short transfer. Retries
 * EINTR/EAGAIN (xwax's SIGCHLD) and transient controller hiccups. */
static int oled_wr(const unsigned char *buf, size_t len)
{
    int tries, saved = 0;

    for (tries = 0; tries < 3; tries++) {
        ssize_t n;
        pthread_mutex_lock(&i2c0_lock);
        n = write(fd, buf, len);
        pthread_mutex_unlock(&i2c0_lock);
        if (n == (ssize_t)len)
            return 0;
        saved = (n < 0) ? errno : EIO;
        usleep(1000);
    }
    errno = saved;
    return -1;
}

/* Send a run of command bytes as ONE I2C transaction: control byte 0x00
 * (Co=0) means "everything up to STOP is a command". */
static int oled_cmds(const unsigned char *cmds, size_t n)
{
    unsigned char b[64];
    if (n + 1 > sizeof b) return -1;
    b[0] = 0x00;
    memcpy(b + 1, cmds, n);
    return oled_wr(b, n + 1);
}

static int oled_cmd(unsigned char c)
{
    return oled_cmds(&c, 1);
}

